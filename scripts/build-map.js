// Builds data/worldmap.js: the 40 × 17 pixel world map, from Natural Earth's
// public-domain 1:110m land outline (via the world-atlas package on jsDelivr).
//
//   node scripts/build-map.js
//
// Only needs re-running to change the map's size or framing. The output is
// committed, so the app never downloads anything.

import { writeFile } from "node:fs/promises";

const SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json";

// The frame: plain longitude/latitude (equirectangular), every longitude, and
// latitudes from the Arctic down to just below South America (no Antarctica).
const COLS = 40;
const ROWS = 17;
const NORTH = 72;
const SOUTH = -56;
const SAMPLES = 4; // per cell, per side
const MIN_LAND = 0.35;

// ── TopoJSON → polygons ────────────────────────────────────────────────────

function decodeArcs(topology) {
  const [sx, sy] = topology.transform.scale;
  const [tx, ty] = topology.transform.translate;
  return topology.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

// Some outlines (Russia, Fiji) cross the 180° line by jumping from +180 to
// −180. On a flat map that jump looks like an edge right across the world, so
// unwrap it: keep counting past 180 instead of jumping back.
function unwrap(points) {
  let shift = 0;
  return points.map(([x, y], i) => {
    if (i > 0) {
      const prev = points[i - 1][0];
      if (x - prev > 180) shift -= 360;
      else if (prev - x > 180) shift += 360;
    }
    return [x + shift, y];
  });
}

function ring(indexes, arcs) {
  const points = [];
  for (const i of indexes) {
    const arc = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return unwrap(points);
}

function polygons(topology) {
  const arcs = decodeArcs(topology);
  const out = [];
  for (const geometry of topology.objects.land.geometries) {
    const parts = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
    for (const rings of parts) out.push(rings.map((r) => ring(r, arcs)));
  }
  return out;
}

// Even-odd rule over every ring of a polygon, so holes (lakes) work too.
function inside([x, y], rings) {
  let hit = false;
  for (const pts of rings) {
    for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
      const [xi, yi] = pts[i];
      const [xj, yj] = pts[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
    }
  }
  return hit;
}

// ── Rasterise ──────────────────────────────────────────────────────────────

const topology = await (await fetch(SOURCE)).json();
const land = polygons(topology);

const rows = [];
for (let r = 0; r < ROWS; r++) {
  let line = "";
  for (let c = 0; c < COLS; c++) {
    let hits = 0;
    for (let i = 0; i < SAMPLES; i++) {
      for (let j = 0; j < SAMPLES; j++) {
        const lon = -180 + ((c + (i + 0.5) / SAMPLES) * 360) / COLS;
        const lat = NORTH - ((r + (j + 0.5) / SAMPLES) * (NORTH - SOUTH)) / ROWS;
        // Unwrapped outlines can run past ±180°, so also look one world over.
        const isLand = [lon, lon + 360, lon - 360].some((x) => land.some((p) => inside([x, lat], p)));
        if (isLand) hits++;
      }
    }
    line += hits / (SAMPLES * SAMPLES) >= MIN_LAND ? "#" : ".";
  }
  rows.push(line);
}

const output = `// Date My Map: the pixel world map. GENERATED by scripts/build-map.js from
// Natural Earth (public domain). Don't edit by hand; re-run the script.
//
// "#" is land, "." is sea. Plain longitude/latitude grid: each column is
// ${360 / COLS}° of longitude, each row ${((NORTH - SOUTH) / ROWS).toFixed(2)}° of latitude, from ${NORTH}°N to ${-SOUTH}°S.

export const MAP_COLS = ${COLS};
export const MAP_ROWS = ${ROWS};

export const LAND = [
${rows.map((r) => `  "${r}",`).join("\n")}
];

// Which cell a place falls in, for the event dots on the timeline.
export function cellAt(lat, lon) {
  const col = Math.floor(((lon + 180) / 360) * MAP_COLS);
  const row = Math.floor(((${NORTH} - lat) / ${NORTH - SOUTH}) * MAP_ROWS);
  return {
    col: Math.min(MAP_COLS - 1, Math.max(0, col)),
    row: Math.min(MAP_ROWS - 1, Math.max(0, row)),
  };
}
`;

await writeFile(new URL("../data/worldmap.js", import.meta.url), output);
console.log(rows.join("\n"));
